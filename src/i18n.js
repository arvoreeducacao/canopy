function locale() {
  let raw = process.env.GALHO_LANG
  if (!raw) {
    try { raw = app.getLocale() } catch { raw = 'en' }
  }
  return (raw || 'en').toLowerCase().startsWith('pt') ? 'pt' : 'en'
}

function t(key, ...args) {
  const dict = STRINGS[locale()] || STRINGS.en
  const value = dict[key] !== undefined ? dict[key] : STRINGS.en[key]
  if (typeof value === 'function') return value(...args)
  return value !== undefined ? value : key
}

module.exports = { t, locale }
